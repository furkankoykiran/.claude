/**
 * Deterministic catalog generator.
 *
 * Reads a ResolvedCatalog (built offline from manifest + lock + cache) and
 * writes every output. Generation is a pure function of its inputs:
 *   - stable sort order
 *   - stable, recursively-sorted JSON keys
 *   - LF line endings, UTF-8, trailing newline
 *   - no wall-clock timestamps anywhere
 *
 * Atomicity: everything is staged in a temp dir first. Only after the full
 * build succeeds do we swap it into place, so a failure leaves the committed
 * outputs untouched.
 */
import { mkdir, writeFile, rm, cp, readFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { join, relative, dirname } from "node:path";
import { createHash } from "node:crypto";
import type {
  Catalog,
  CatalogSkillEntry,
  Lockfile,
  ResolvedSkill,
} from "./types.ts";
import type { ResolvedCatalog } from "./resolver.ts";
import { skillSortKey } from "./resolver.ts";
import { info } from "./log.ts";
import type { DiffReport } from "./diff.ts";

const CATALOG_SCHEMA_VERSION = 1;
const GENERATED_BANNER = "<!-- AUTO-GENERATED by `bun run catalog:generate` — do not edit directly. -->";

/** Recursively sort object keys for stable JSON. Arrays keep order. */
export function stableJson(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(stableJson);
  if (value && typeof value === "object") {
    const out: Record<string, unknown> = {};
    for (const k of Object.keys(value as Record<string, unknown>).sort()) {
      out[k] = stableJson((value as Record<string, unknown>)[k]);
    }
    return out;
  }
  return value;
}

export function jsonString(value: unknown): string {
  return JSON.stringify(stableJson(value), null, 2) + "\n";
}

/** Sanitize a string into a collision-safe path segment. */
function safeSeg(s: string): string {
  const seg = s.replace(/[^a-z0-9-]+/gi, "-").replace(/^-+|-+$/g, "").toLowerCase();
  return seg || "unnamed";
}

export function skillPagePath(skill: ResolvedSkill): string {
  return `docs/skills/${safeSeg(skill.sourceId)}/${safeSeg(skill.skillName)}.md`;
}

function sortedSkills(skills: ResolvedSkill[]): ResolvedSkill[] {
  return [...skills].sort((a, b) => skillSortKey(a).localeCompare(skillSortKey(b)));
}

// ---------------------------------------------------------------------------
// Per-skill page
// ---------------------------------------------------------------------------

export function renderSkillPage(skill: ResolvedSkill): string {
  const lines: string[] = [];
  lines.push(GENERATED_BANNER);
  lines.push(`<!-- Regenerate: bun run catalog:generate -->`);
  lines.push(`<!-- Source: ${skill.sourceId} · revision ${skill.resolvedRevision ?? "n/a"} -->`);
  lines.push(`<!-- Redistribution: ${skill.license.redistribution} (declared ${skill.license.declared}, detected ${skill.license.detected}) -->`);
  lines.push("");
  lines.push(`# ${skill.canonicalInvocation}`);
  lines.push("");

  if (skill.unresolvedReason) {
    lines.push(`> **Runtime-only component** — not deterministically resolvable from a git ref.`);
    lines.push(`> ${skill.unresolvedReason}`);
    lines.push("");
  }

  const meta: Array<[string, string]> = [];
  if (skill.skillName) meta.push(["skill-name", skill.skillName]);
  meta.push(["source", skill.sourceId]);
  meta.push(["pack", skill.pack]);
  if (skill.repo) meta.push(["repo", skill.repo]);
  if (skill.ref) meta.push(["ref", skill.ref]);
  if (skill.resolvedRevision) meta.push(["resolved-revision", skill.resolvedRevision]);
  meta.push(["relative-path", skill.relativePath || "(runtime)"]);
  if (skill.version) meta.push(["version", skill.version]);
  if (skill.preambleTier !== undefined) meta.push(["preamble-tier", String(skill.preambleTier)]);
  if (skill.allowedTools?.length) meta.push(["allowed-tools", skill.allowedTools.join(", ")]);
  if (skill.disallowedTools?.length) meta.push(["disallowed-tools", skill.disallowedTools.join(", ")]);
  meta.push(["digest", `sha256:${skill.digest}`]);
  meta.push(["redistribution", skill.license.redistribution]);
  if (skill.license.note) meta.push(["license-note", skill.license.note]);
  if (skill.security.flags.length) meta.push(["security-flags", skill.security.flags.join(", ")]);

  lines.push("| field | value |");
  lines.push("| --- | --- |");
  for (const [k, v] of meta) lines.push(`| ${k} | ${v} |`);
  lines.push("");

  if (skill.description) {
    lines.push("## Description");
    lines.push("");
    lines.push(skill.description);
    lines.push("");
  }
  if (skill.whenToUse) {
    lines.push("## When to use");
    lines.push("");
    lines.push(skill.whenToUse);
    lines.push("");
  }

  if (skill.license.redistribution === "full" && skill.body.trim()) {
    lines.push("## Original frontmatter");
    lines.push("");
    lines.push("```yaml");
    lines.push(skill.rawFrontmatter || "(none)");
    lines.push("```");
    lines.push("");
    lines.push("## Instructions");
    lines.push("");
    lines.push(skill.body.trim());
    lines.push("");
  } else {
    lines.push("## Content");
    lines.push("");
    lines.push("Full body omitted from this catalog (redistribution is metadata-only).");
    if (skill.repo && skill.resolvedRevision) {
      lines.push(`Read it at the immutable revision: ${skill.repo}/tree/${skill.resolvedRevision}/${skill.relativePath.replace(/\/[^/]*$/, "")}`);
    }
    lines.push("");
  }

  if (skill.warnings.length) {
    lines.push("## Validation warnings");
    lines.push("");
    for (const w of skill.warnings) lines.push(`- ${w}`);
    lines.push("");
  }

  lines.push("---");
  lines.push("");
  lines.push("*Generated by the Skills Catalog resolver. Edit the upstream source, then rerun `bun run catalog:generate`.*");
  lines.push("");
  return lines.join("\n");
}

// ---------------------------------------------------------------------------
// Index (SKILLS_CATALOG.md)
// ---------------------------------------------------------------------------

export function renderIndex(resolved: ResolvedCatalog): string {
  const skills = sortedSkills(resolved.skills);
  const lines: string[] = [GENERATED_BANNER, "<!-- Regenerate: bun run catalog:generate -->", ""];
  lines.push("# Skills Catalog");
  lines.push("");
  lines.push(`Generated index of every Claude Code skill, command, and runtime component represented by \`furkankoykiran/.claude\`.`);
  lines.push(`Resolver version ${resolved.lock.resolverVersion} · schema v${CATALOG_SCHEMA_VERSION}.`);
  lines.push("");
  lines.push(`- **Sources:** ${resolved.sourceMeta.length}`);
  lines.push(`- **Skills / entries:** ${skills.length}`);
  lines.push(`- **Redistributable (full body):** ${skills.filter((s) => s.license.redistribution === "full").length}`);
  lines.push(`- **Runtime-only:** ${resolved.sourceMeta.filter((s) => s.runtimeOnly).length}`);
  lines.push("");

  // Group by source in stable (id) order.
  const bySource = new Map<string, ResolvedSkill[]>();
  for (const s of skills) {
    const arr = bySource.get(s.sourceId) ?? [];
    arr.push(s);
    bySource.set(s.sourceId, arr);
  }
  const sourceOrder = [...resolved.sourceMeta].sort((a, b) => a.id.localeCompare(b.id));

  for (const sm of sourceOrder) {
    const arr = (bySource.get(sm.id) ?? []).sort((a, b) => a.canonicalInvocation.localeCompare(b.canonicalInvocation));
    const meta = resolved.sourceMeta.find((m) => m.id === sm.id)!;
    lines.push(`## ${meta.displayName}`);
    lines.push("");
    lines.push(`type: \`${meta.type}\` · pack: \`${meta.pack}\` · skills: ${arr.length} · redistribution: ${meta.redistribution}`);
    if (meta.repo && meta.resolvedRevision) {
      lines.push(`repo: ${meta.repo} · ref: \`${meta.ref}\` · revision: \`${meta.resolvedRevision.slice(0, 12)}\``);
    }
    if (meta.runtimeOnly) lines.push(`_Runtime-only — see notes below._`);
    lines.push("");
    if (arr.length === 0) {
      lines.push("_(no resolvable skills)_");
      lines.push("");
      continue;
    }
    lines.push("| invocation | description | redistribution |");
    lines.push("| --- | --- | --- |");
    for (const s of arr) {
      const desc = (s.description ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ").slice(0, 120);
      // relative() from the CONTAINING DIRECTORY. Passing the file path
      // itself treats the filename as a directory and emits one extra "..",
      // which is why every link in the published SKILLS_CATALOG.md pointed
      // above the repository root.
      const link = `[${s.canonicalInvocation}](${relative(dirname(`${GENERATED_DIR}/SKILLS_CATALOG.md`), skillPagePath(s))})`;
      lines.push(`| ${link} | ${desc} | ${s.license.redistribution} |`);
    }
    lines.push("");
  }

  if (resolved.warnings.length) {
    lines.push("## Warnings");
    lines.push("");
    for (const w of [...new Set(resolved.warnings)].sort()) lines.push(`- ${w}`);
    lines.push("");
  }

  lines.push("---");
  lines.push("");
  lines.push("*Regenerate with `bun run catalog:generate`. See `docs/catalog-architecture.md` for the discovery model.*");
  lines.push("");
  return lines.join("\n");
}

